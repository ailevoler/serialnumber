<?php
require dirname(__DIR__) . '/includes/bootstrap.php';
$me = require_admin();

$types = earning_types();
$type = array_key_exists(input('type'), $types) ? input('type') : '';
$user = strtolower(input('user'));
$from = input('from');
$to = input('to');

$where = ['1=1'];
$params = [];
if ($type) { $where[] = 'e.type = ?'; $params[] = $type; }
if ($user !== '') { $where[] = 'u.username = ?'; $params[] = $user; }
if ($from) { $where[] = 'e.created_at >= ?'; $params[] = $from . ' 00:00:00'; }
if ($to) { $where[] = 'e.created_at <= ?'; $params[] = $to . ' 23:59:59'; }
$w = implode(' AND ', $where);
$base = "FROM earnings e JOIN users u ON u.id = e.user_id LEFT JOIN users s ON s.id = e.source_user_id WHERE $w";

if (input('export') === 'csv') {
    $rows = q_all("SELECT e.id, e.created_at, u.username, e.type, e.amount, s.username src, e.description, e.paid_to $base ORDER BY e.id DESC", $params);
    csv_download('xgen-commissions-' . date('Ymd') . '.csv', ['ID', 'Date', 'Member', 'Type', 'Amount', 'Source', 'Description', 'Credited To'], $rows);
}
$p = paginate("SELECT COUNT(*) $base", $params, 30);
$rows = q_all("SELECT e.*, u.username, s.username source $base ORDER BY e.id DESC LIMIT {$p['limit']} OFFSET {$p['offset']}", $params);
$byType = array_column(q_all("SELECT e.type, SUM(e.amount) t $base GROUP BY e.type", $params), 't', 'type');

page_header('Commissions', $me, 'All income generated by the compensation plan');
?>
<div class="earn-grid mb-2">
  <?php foreach ($types as $k => $t): ?>
    <a class="earn-item" href="?<?= e(http_build_query(array_merge($_GET, ['type' => $k, 'page' => 1]))) ?>" style="<?= $type === $k ? 'border-color:var(--green)' : '' ?>">
      <div class="earn-ic"><?= icon($t['icon']) ?></div><span><?= e($t['label']) ?></span><strong><?= money($byType[$k] ?? 0) ?></strong>
    </a>
  <?php endforeach; ?>
</div>
<div class="card">
  <div class="card-header">
    <form class="filters" method="get">
      <select class="input" name="type"><option value="">All types</option><?php foreach ($types as $k => $t): ?><option value="<?= $k ?>" <?= $type === $k ? 'selected' : '' ?>><?= e($t['label']) ?></option><?php endforeach; ?></select>
      <input class="input" name="user" value="<?= e($user) ?>" placeholder="Username">
      <input class="input" type="date" name="from" value="<?= e($from) ?>" aria-label="From">
      <input class="input" type="date" name="to" value="<?= e($to) ?>" aria-label="To">
      <button class="btn btn-primary btn-sm">Filter</button>
      <button class="btn btn-light btn-sm" name="export" value="csv"><?= icon('download', 14) ?> CSV</button>
    </form>
  </div>
  <div class="card-body p-0 table-wrap">
    <table class="table stack">
      <thead><tr><th>Date</th><th>Member</th><th>Type</th><th>Description</th><th>Source</th><th>Credited to</th><th class="text-right">Amount</th></tr></thead>
      <tbody>
      <?php foreach ($rows as $r): ?>
        <tr>
          <td class="nowrap"><?= fdatetime($r['created_at']) ?></td>
          <td>@<?= e($r['username']) ?></td>
          <td><span class="badge badge-<?= $r['credited'] ? 'success' : 'gold' ?>"><?= e($types[$r['type']]['label']) ?></span></td>
          <td><?= e($r['description']) ?></td>
          <td><?= $r['source'] ? '@' . e($r['source']) : '—' ?></td>
          <td><?= paid_to_badge($r['paid_to']) ?></td>
          <td class="text-right amount-plus"><?= money($r['amount']) ?></td>
        </tr>
      <?php endforeach; ?>
      <?php if (!$rows) echo empty_row(7); ?>
      </tbody>
    </table>
  </div>
  <?= pagination_links($p) ?>
</div>
<?php page_footer();
